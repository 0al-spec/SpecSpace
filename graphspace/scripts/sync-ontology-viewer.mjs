import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import postcss from 'postcss';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const slice = path.join(root, 'src/entities/ontology-diagram');
const manifest = JSON.parse(readFileSync(path.join(slice, 'upstream.json'), 'utf8'));
const args = process.argv.slice(2);
if (!(args.length === 1 && args[0] === '--check') && !(args.length === 2 && args[0] === '--source')) {
  throw new Error('Use --check or --source /path/to/Ontology');
}
for (const [name, entry] of Object.entries(manifest.files)) {
  const destination = path.join(slice, 'lib/upstream', name);
  const bytes = args[0] === '--source'
    ? execFileSync('git', ['-C', args[1], 'show', `${manifest.revision}:${entry.source}`])
    : readFileSync(destination);
  if (createHash('sha256').update(bytes).digest('hex') !== entry.sha256) throw new Error(`Upstream hash mismatch: ${name}`);
  if (args[0] === '--source') writeFileSync(destination, bytes);
}
const css = postcss.parse(readFileSync(path.join(slice, 'lib/upstream/style.css'), 'utf8'));
css.walkAtRules(rule => { if (rule.name !== 'media') throw new Error(`Review unsupported upstream CSS at-rule: ${rule.name}`); });
css.walkRules(rule => {
  // All upstream rules, including those inside media queries, stay inside the host.
  // Root/body document styles have no place in an embedded component.
  if (rule.selectors.some(selector => [':root', 'body'].includes(selector))) { rule.remove(); return; }
  rule.selectors = rule.selectors.map(selector => `:where(.ontology-explorer) ${selector}`);
});
const scoped = '/* Generated by scripts/sync-ontology-viewer.mjs. Do not edit. */\n' + css.toString();
const output = path.join(slice, 'ui/upstream.scoped.css');
if (args[0] === '--check') {
  if (readFileSync(output, 'utf8') !== scoped) throw new Error('Scoped CSS is out of date');
} else { mkdirSync(path.dirname(output), { recursive: true }); writeFileSync(output, scoped); }
console.log(`Ontology Viewer ${manifest.revision}: source hashes and scoped CSS verified`);
